/**
 * Writes lib/sample-hashes.ts: SHA-256 of each sample PNG.
 *   node scripts/hash-samples.mjs
 * The server uses these so Demo mode only ever serves pre-saved results for an image that
 * is byte-for-byte one of OUR synthetic samples (never for a real upload that merely claims
 * to be a sample). Re-run after scripts/make-samples.mjs.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { SAMPLES } = await import(pathToFileURL(path.join(root, "lib", "samples.ts")).href);

const lines = SAMPLES.map((s) => {
  const hash = createHash("sha256").update(readFileSync(path.join(root, "public", s.image))).digest("hex");
  return `  "${hash}": "${s.id}",`;
});
writeFileSync(
  path.join(root, "lib", "sample-hashes.ts"),
  `// GENERATED by scripts/hash-samples.mjs - do not edit by hand.\n` +
    `/** SHA-256 of each synthetic sample image -> sample id. */\n` +
    `export const SAMPLE_HASHES: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
  "utf8",
);
console.log(`wrote lib/sample-hashes.ts (${SAMPLES.length} samples)`);
